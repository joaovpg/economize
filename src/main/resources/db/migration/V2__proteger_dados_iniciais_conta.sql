CREATE FUNCTION FN002_PROTEGER_DADOS_INICIAIS() RETURNS TRIGGER
LANGUAGE PLPGSQL
AS $FUNCTION$
BEGIN
    IF OLD.BOL_DADOS_INICIAIS_BLOQUEADOS AND NOT NEW.BOL_DADOS_INICIAIS_BLOQUEADOS THEN
        RAISE EXCEPTION 'O bloqueio dos dados iniciais da conta e irreversivel';
    END IF;

    IF OLD.BOL_DADOS_INICIAIS_BLOQUEADOS AND (
        NEW.STR_MOEDA IS DISTINCT FROM OLD.STR_MOEDA
        OR NEW.DEC_SALDO_INICIAL IS DISTINCT FROM OLD.DEC_SALDO_INICIAL
        OR NEW.DAT_SALDO_INICIAL IS DISTINCT FROM OLD.DAT_SALDO_INICIAL
    ) THEN
        RAISE EXCEPTION 'Os dados iniciais da conta estao bloqueados';
    END IF;

    RETURN NEW;
END;
$FUNCTION$;

CREATE TRIGGER TG002_01_PROTEGER_DADOS_INICIAIS
BEFORE UPDATE ON TB002_CONTA_FINANCEIRA
FOR EACH ROW EXECUTE FUNCTION FN002_PROTEGER_DADOS_INICIAIS();

CREATE FUNCTION FN006_VALIDAR_CONTA_TRANSACAO() RETURNS TRIGGER
LANGUAGE PLPGSQL
AS $FUNCTION$
DECLARE
    CONTA TB002_CONTA_FINANCEIRA%ROWTYPE;
BEGIN
    SELECT * INTO CONTA
    FROM TB002_CONTA_FINANCEIRA
    WHERE ID_REGISTRO = NEW.ID_CONTA_FINANCEIRA
    FOR UPDATE;

    IF FOUND THEN
        IF TG_OP = 'INSERT' AND NOT CONTA.BOL_ATIVO THEN
            RAISE EXCEPTION 'Novas transacoes exigem conta ativa';
        ELSIF TG_OP = 'UPDATE'
              AND NEW.ID_CONTA_FINANCEIRA IS DISTINCT FROM OLD.ID_CONTA_FINANCEIRA
              AND NOT CONTA.BOL_ATIVO THEN
            RAISE EXCEPTION 'Uma nova associacao exige conta ativa';
        END IF;

        IF NEW.DAT_VENCIMENTO < CONTA.DAT_SALDO_INICIAL THEN
            RAISE EXCEPTION 'A data financeira e anterior a data do saldo inicial da conta';
        END IF;
    END IF;

    RETURN NEW;
END;
$FUNCTION$;

CREATE TRIGGER TG006_01_VALIDAR_CONTA
BEFORE INSERT OR UPDATE OF ID_CONTA_FINANCEIRA, DAT_VENCIMENTO ON TB006_TRANSACAO
FOR EACH ROW EXECUTE FUNCTION FN006_VALIDAR_CONTA_TRANSACAO();

