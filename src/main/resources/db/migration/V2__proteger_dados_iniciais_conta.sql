ALTER TABLE TB002_CONTA_FINANCEIRA
    ADD COLUMN BOL_DADOS_INICIAIS_BLOQUEADOS BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE TB002_CONTA_FINANCEIRA CONTA
SET BOL_DADOS_INICIAIS_BLOQUEADOS = TRUE
WHERE EXISTS (
    SELECT 1
    FROM TB006_TRANSACAO TRANSACAO
    WHERE TRANSACAO.ID_CONTA_FINANCEIRA = CONTA.ID_REGISTRO
) OR EXISTS (
    SELECT 1
    FROM TB005_SEGMENTO_RECORRENCIA SEGMENTO
    WHERE SEGMENTO.ID_CONTA_FINANCEIRA = CONTA.ID_REGISTRO
);

DO $BLOCK$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM TB006_TRANSACAO TRANSACAO
        JOIN TB002_CONTA_FINANCEIRA CONTA ON CONTA.ID_REGISTRO = TRANSACAO.ID_CONTA_FINANCEIRA
        WHERE TRANSACAO.DAT_VENCIMENTO < CONTA.DAT_SALDO_INICIAL
    ) OR EXISTS (
        SELECT 1
        FROM TB005_SEGMENTO_RECORRENCIA SEGMENTO
        JOIN TB002_CONTA_FINANCEIRA CONTA ON CONTA.ID_REGISTRO = SEGMENTO.ID_CONTA_FINANCEIRA
        WHERE SEGMENTO.DAT_DTSTART < CONTA.DAT_SALDO_INICIAL
    ) THEN
        RAISE EXCEPTION 'Existem operacoes anteriores a data do saldo inicial da conta';
    END IF;
END;
$BLOCK$;

