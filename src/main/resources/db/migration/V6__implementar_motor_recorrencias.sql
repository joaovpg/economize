ALTER TABLE TB006_TRANSACAO
    ADD CONSTRAINT CK006_06_EXCECAO CHECK (
        (
            BOL_EXCECAO_RECORRENCIA
            AND ID_GRUPO_RECORRENCIA IS NOT NULL
            AND (
                (ID_SEGMENTO_RECORRENCIA IS NULL AND DAT_IDENTIFICADOR_RECORRENCIA IS NULL)
                OR (ID_SEGMENTO_RECORRENCIA IS NOT NULL AND DAT_IDENTIFICADOR_RECORRENCIA IS NOT NULL)
            )
        )
        OR (
            NOT BOL_EXCECAO_RECORRENCIA
            AND (
                (ID_GRUPO_RECORRENCIA IS NULL AND ID_SEGMENTO_RECORRENCIA IS NULL AND DAT_IDENTIFICADOR_RECORRENCIA IS NULL)
                OR (ID_GRUPO_RECORRENCIA IS NOT NULL AND ID_SEGMENTO_RECORRENCIA IS NOT NULL AND DAT_IDENTIFICADOR_RECORRENCIA IS NOT NULL)
            )
        )
    );

