            INT_NUMERO_PRIMEIRA_PARCELA IS NOT NULL
            AND INT_QUANTIDADE_TOTAL_ORIGINAL IS NOT NULL
            AND INT_NUMERO_PRIMEIRA_PARCELA <= INT_QUANTIDADE_TOTAL_ORIGINAL
        )
    );

